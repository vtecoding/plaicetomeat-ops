export function translateOperatorError(locale: OperatorLocale, message: string | null | undefined): string {
  if (!message) return translateOperator(locale, "error.generic");
  if (message.startsWith("i18n:")) {
    const key = message.slice(5) as OperatorTranslationKey;
    if (key in en) return translateOperator(locale, key);
  }
  const match = MESSAGE_KEYS.find(([pattern]) => pattern.test(message));
  return translateOperator(locale, match?.[1] ?? "error.generic");
}
