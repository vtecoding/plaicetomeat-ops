export const operatorResources: Record<OperatorLocale, Record<OperatorTranslationKey, string>> = {
  en,
  "ps-AF": ps,
};

export function isOperatorLocale(value: string | null | undefined): value is OperatorLocale {
  return value === "en" || value === "ps-AF";
}

export function isOperatorScriptStyle(value: string | null | undefined): value is OperatorScriptStyle {
  return value === "clear" || value === "nastaliq";
}

export function operatorDirection(locale: OperatorLocale): "ltr" | "rtl" {
  return locale === "ps-AF" ? "rtl" : "ltr";
}

export function translateOperator(
  locale: OperatorLocale,
  key: OperatorTranslationKey,
  values: Record<string, string | number> = {},
): string {
  const value = operatorResources[locale][key] ?? en[key];
  if (!value) {
    throw new Error(`Missing operator translation: ${locale}:${key}`);
  }
  return value.replace(/\{([A-Za-z0-9_]+)\}/g, (_, name: string) => {
    if (!(name in values)) {
      throw new Error(`Missing operator interpolation: ${locale}:${key}:${name}`);
    }
    return String(values[name]);
  });
}

export function isolateLtr(value: string | number): string {
  return `\u2066${value}\u2069`;
}

export function operatorMoney(value: number, locale: OperatorLocale = "en"): string {
  const formatted = `£${value.toFixed(2)}`;
  return locale === "ps-AF" ? isolateLtr(formatted) : formatted;
}

export function operatorMeasure(value: string | number, unit: string, locale: OperatorLocale = "en"): string {
  const formatted = `${value} ${unit}`;
  return locale === "ps-AF" ? isolateLtr(formatted) : formatted;
}

