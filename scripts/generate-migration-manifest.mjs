#!/usr/bin/env node
/**
 * Deterministic migration manifest generator (PTM-OBS-012 fix).
 *
 * Replaces the hand-curated 11-row `expected_migrations` table as the source of
 * truth for "is production at the release migration head?". The manifest is
 * derived mechanically from EVERY file in supabase/migrations, so it can never
 * silently omit a security-critical migration the way the curated table did.
 *
 * Output: src/lib/server/migration-manifest.generated.ts — a committed constant
 * consumed by:
 *   - /api/health          (runtime version parity vs get_applied_migration_versions)
 *   - the release gate      (checksum parity vs the deployed repo tree)
 *   - verify:migration-manifest (drift guard: regenerate and diff)
 *
 * Runtime parity is VERSION-based (the applied ledger exposes versions, not
 * per-file hashes). CHECKSUM parity is enforced at CI/release time where the
 * repo files are available. Both derive from this one generated file.
 *
 * Usage:
 *   node scripts/generate-migration-manifest.mjs            # write the file
 *   node scripts/generate-migration-manifest.mjs --check    # fail if out of date
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import process from "node:process";

const MIGRATIONS_DIR = join(process.cwd(), "supabase", "migrations");
const OUT_FILE = join(process.cwd(), "src", "lib", "server", "migration-manifest.generated.ts");

function build() {
  const files = readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith(".sql"))
    .sort();

  const migrations = files.map((file) => {
    const version = file.slice(0, file.indexOf("_"));
    if (!/^\d{12}$/.test(version)) {
      throw new Error(`Migration filename does not start with a 12-digit version: ${file}`);
    }
    // Normalize CRLF -> LF so the checksum is content-based and stable across
    // Windows (local) and Linux (CI) checkouts — otherwise line-ending conversion
    // alone would flip the checksum and spuriously fail the release gate.
    const sql = readFileSync(join(MIGRATIONS_DIR, file), "utf8").replace(/\r\n/g, "\n");
    const checksum = createHash("sha256").update(sql).digest("hex");
    return { version, file, checksum };
  });

  const versions = migrations.map((m) => m.version);
  const dupes = versions.filter((v, i) => versions.indexOf(v) !== i);
  if (dupes.length) throw new Error(`Duplicate migration versions: ${dupes.join(", ")}`);

  const requiredHead = versions[versions.length - 1] ?? "";
  // A single combined checksum over "version:file:checksum" lines — changes if any
  // migration file's content, name, or ordering changes.
  const manifestChecksum = createHash("sha256")
    .update(migrations.map((m) => `${m.version}:${m.file}:${m.checksum}`).join("\n"))
    .digest("hex");

  return { migrations, versions, requiredHead, manifestChecksum };
}

function render({ migrations, versions, requiredHead, manifestChecksum }) {
  return `// @generated by scripts/generate-migration-manifest.mjs — DO NOT EDIT BY HAND.
// Regenerate with: node scripts/generate-migration-manifest.mjs
//
// The complete, mechanically-derived set of migrations that define the production
// release head. This is the deterministic replacement for the hand-curated
// \`expected_migrations\` table (PTM-OBS-012), so migration parity can never again
// report green while security-critical migrations are missing from production.

export type MigrationManifestEntry = {
  version: string;
  file: string;
  checksum: string;
};

export const REQUIRED_MIGRATIONS: readonly MigrationManifestEntry[] = ${JSON.stringify(migrations, null, 2)} as const;

export const REQUIRED_MIGRATION_VERSIONS: readonly string[] = ${JSON.stringify(versions, null, 2)} as const;

export const REQUIRED_MIGRATION_HEAD = ${JSON.stringify(requiredHead)} as const;

export const MIGRATION_MANIFEST_CHECKSUM = ${JSON.stringify(manifestChecksum)} as const;

export const REQUIRED_MIGRATION_COUNT = ${migrations.length} as const;
`;
}

const built = build();
const rendered = render(built);
const isCheck = process.argv.includes("--check");

if (isCheck) {
  let current = "";
  try {
    current = readFileSync(OUT_FILE, "utf8");
  } catch {
    current = "";
  }
  if (current !== rendered) {
    console.error(
      "migration-manifest: OUT OF DATE. Run `node scripts/generate-migration-manifest.mjs` and commit the result.",
    );
    process.exit(1);
  }
  console.log(
    `migration-manifest: up to date (${built.migrations.length} migrations, head ${built.requiredHead}).`,
  );
  process.exit(0);
}

writeFileSync(OUT_FILE, rendered);
console.log(
  `migration-manifest: wrote ${built.migrations.length} migrations (head ${built.requiredHead}, checksum ${built.manifestChecksum.slice(0, 12)}…).`,
);
